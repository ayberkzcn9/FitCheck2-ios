String jsonKacis(String metin) => metin
    .replaceAll(r'\', r'\\')
    .replaceAll('"', r'\"')
    .replaceAll('\n', r'\n')
    .replaceAll('\r', '');

String yerTutucuBlogu(String anahtar, Map<String, String> tutucular) {
  final girisler = tutucular.entries
      .map((giris) => '      "${jsonKacis(giris.key)}": {\n'
          '        "type": "${giris.value}"\n'
          '      }')
      .join(',\n');
  return '  "@$anahtar": {\n'
      '    "placeholders": {\n'
      '$girisler\n'
      '    }\n'
      '  }';
}

void main() {
  if (anahtarlar.length != metinler['tr']!.length) {
    stderr.writeln('Anahtar/değer sayısı uyuşmuyor.');
    exitCode = 1;
    return;
  }

  final klasor = Directory('lib/l10n');
  final dosyalar = klasor
      .listSync()
      .whereType<File>()
      .where((f) => RegExp(r'app_[a-z]{2}\.arb$').hasMatch(f.path))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  for (final dosya in dosyalar) {
    final dil =
        RegExp(r'app_([a-z]{2})\.arb$').firstMatch(dosya.path)!.group(1)!;
    final degerler = metinler[dil];

    if (degerler == null || degerler.length != anahtarlar.length) {
      stderr.writeln('Dil tablosu eksik/hatalı: $dil');
      exitCode = 1;
      continue;
    }

    var metin = dosya.readAsStringSync();
    final eklenecekler = <String>[];

    for (var i = 0; i < anahtarlar.length; i++) {
      final anahtar = anahtarlar[i];
      if (RegExp('"${RegExp.escape(anahtar)}":').hasMatch(metin)) continue;
      eklenecekler.add('  "$anahtar": "${jsonKacis(degerler[i])}"');
      final tutucular = yerTutucular[anahtar];
      if (tutucular != null) {
        eklenecekler.add(yerTutucuBlogu(anahtar, tutucular));
      }
    }

    if (eklenecekler.isNotEmpty) {
      final kapanisIndex = metin.lastIndexOf('}');
      var govde = metin.substring(0, kapanisIndex);
      final kapanis = metin.substring(kapanisIndex);
      govde = govde.replaceAll(RegExp(r'[\s,]+$'), '');
      metin = '$govde,\n${eklenecekler.join(',\n')}\n$kapanis';
    }

    // Yazmadan önce geçerliliğini doğrula.
    jsonDecode(metin);
    dosya.writeAsStringSync(metin, flush: true);
    stdout.writeln('$dil: ${eklenecekler.length} satır eklendi');
  }
}
